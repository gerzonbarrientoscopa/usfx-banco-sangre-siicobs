export function reportToday(query) {
  return request({
    url: '/discard-today-pdf/',
    method: 'get',
    params: query,
    headers: {
      'Access-Control-Allow-Origin': '*',
      'Content-Type': 'application/pdf',
      'Accept': 'application/pdf',
      'Content-Disposition': 'attachment'
    },
    responseType: 'arraybuffer'
  })
}

